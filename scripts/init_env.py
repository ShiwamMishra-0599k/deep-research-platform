"""Generate a git-ignored .env with strong random secrets for docker compose.

    python scripts/init_env.py            # creates .env if it does not exist
    python scripts/init_env.py --path X   # write somewhere else

Never overwrites an existing file and never prints a secret. Passwords are hex so they are safe to
embed in DATABASE_URL without URL-encoding.
"""
import argparse
import secrets
import sys
from pathlib import Path

TEMPLATE = """# Generated by scripts/init_env.py -- git-ignored; do not commit or share.
JWT_SECRET={jwt}
AGENT_API_KEY={agent}
POSTGRES_PASSWORD={pg}

# Optional
# RATE_LIMIT_FAIL_MODE=local        # or "closed": refuse login/register/research when Redis is down
# TRUSTED_PROXY_CIDRS=10.0.0.0/8    # ONLY your own reverse proxies (their X-Forwarded-For is then believed)
# CORS_ALLOWED_ORIGINS=https://app.example.com
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--path", default=str(Path(__file__).resolve().parent.parent / ".env"))
    args = ap.parse_args()
    path = Path(args.path)
    if path.exists():
        print(f"{path} already exists; not touching it. Delete it first if you really want new secrets "
              f"(and rotate the database password with scripts/rotate_db_password.py, not by editing .env).")
        return 1
    path.write_text(
        TEMPLATE.format(jwt=secrets.token_urlsafe(48), agent=secrets.token_urlsafe(32), pg=secrets.token_hex(24)),
        encoding="utf-8",
    )
    try:
        path.chmod(0o600)
    except OSError:
        pass
    print(f"wrote {path} (3 secrets generated, none displayed)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
